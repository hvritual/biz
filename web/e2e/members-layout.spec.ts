test('member task: guidance and state confirmation remain readable at four viewports', async ({ page }, info) => {
  mkdirSync('screenshots/member-task', { recursive: true })
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  for (const viewport of [{ width: 1366, height: 768 }, { width: 1440, height: 900 }, { width: 1536, height: 1024 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    await ready(page)
    const help = page.getByRole('button', { name: '如何查找和管理成员', exact: true })
    await help.focus(); await page.keyboard.press('Enter')
    await expect(help).toHaveAttribute('aria-expanded', 'true')
    await expect(page.locator('#member-task-help')).toContainText('不会勾选')
    await page.screenshot({ path: `screenshots/member-task/members-${viewport.width}-guidance.png`, fullPage: true })
    await page.getByRole('button', { name: '查看 李四', exact: true }).click()
    await expect(page.locator('.member-detail-panel')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
    await page.screenshot({ path: `screenshots/member-task/members-${viewport.width}-detail.png`, fullPage: true })
    await page.keyboard.press('Escape')
    await expect(page.locator('.member-detail-panel')).toHaveCount(0)
    await page.getByLabel('选择 李四', { exact: true }).check()
    await page.getByRole('button', { name: '批量停用', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '批量停用成员', exact: true })
    await expect(dialog).toContainText('李四')
    await expect(dialog.getByLabel('操作原因', { exact: true })).toBeVisible()
    await page.screenshot({ path: `screenshots/member-task/members-${viewport.width}-confirmation.png`, fullPage: true })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByLabel('选择 李四', { exact: true }).uncheck()
    await help.click()
  }
  expect(errors).toEqual([])
  await info.attach('member-task-scope', { body: Buffer.from(JSON.stringify({ evidence: 'DEMO_BROWSER_ONLY', viewports: 4, user_measurement: 'NOT_PERFORMED', native_200_percent_zoom: 'NOT_PERFORMED' })), contentType: 'application/json' })
})

