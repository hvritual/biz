test('member task: filtered sorted paginated list and scroll survive a keyboard detail round trip', async ({ page }) => {
  await page.setViewportSize({ width: 1536, height: 1024 })
  await ready(page)
  await page.getByLabel('搜索成员', { exact: true }).fill('@example.com')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('button', { name: /按.*加入时间.*排序/ }).click()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  const rows = page.locator('.member-table tbody tr')
  const rowIds = await rows.evaluateAll((items) => items.map((item) => item.getAttribute('data-member-id')))
  const second = rows.nth(1)
  await second.getByRole('checkbox').check()
  const name = await second.locator('.identity-copy strong').innerText()
  const view = second.getByRole('button', { name: `查看 ${name}`, exact: true })
  await view.scrollIntoViewIfNeeded()
  await view.focus()
  const before = await page.getByTestId('main-content').evaluate((el) => ({ top: el.scrollTop, left: el.scrollLeft }))
  await page.keyboard.press('Enter')
  await expect(page.locator('.member-detail-panel')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(view).toBeFocused()
  await expect(second.getByRole('checkbox')).toBeChecked()
  await expect(page.getByLabel('搜索成员', { exact: true })).toHaveValue('@example.com')
  expect(await rows.evaluateAll((items) => items.map((item) => item.getAttribute('data-member-id')))).toEqual(rowIds)
  await expect(page.locator('.page-number[aria-current="page"]')).toHaveText('2')
  const after = await page.getByTestId('main-content').evaluate((el) => ({ top: el.scrollTop, left: el.scrollLeft }))
  expect(Math.abs(after.top - before.top)).toBeLessThanOrEqual(1)
  expect(after.left).toBe(before.left)
})

